"""Summarise Monkey's Audio files (.ape) as JSON.

    python3 macinfo.py album.ape [more files ...]
"""
import json
import struct
import sys

from mackit.mac import MacError, parse


def main(paths):
    out = []
    for path in paths:
        try:
            with open(path, "rb") as fh:
                out.append({"file": path, **parse(fh.read())})
        except (OSError, MacError, ValueError, IndexError, struct.error) as exc:
            out.append({"file": path, "error": str(exc)})
    json.dump(out, sys.stdout, ensure_ascii=False, indent=1)
    print()


if __name__ == "__main__":
    main(sys.argv[1:])
